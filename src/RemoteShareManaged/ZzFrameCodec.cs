    /// <summary>
    /// Build a port 50001 command packet from a template.
    /// dec[5] = helloAckNonce ^ K (K passed explicitly — do NOT compute from template,
    /// as templates were captured with nonce=0x46 so template[14]^template[12] = 0x46^K).
    ///
    /// ALL port 50001 packets use check_extra=0x01:
    ///   raw[8] = (seq ^ NonceB(seq)) ^ 0x01
    /// Confirmed for types 0x16, 0x15, 0x12, 0x21–0x3f upload pages.
    /// </summary>
    public static byte[] BuildCatCmd(ReadOnlySpan<byte> template, byte seq,
                                      byte helloAckNonce, byte K)
    {
        byte[] frame = template.ToArray();
        byte nonceB = NonceB(seq);
        frame[6] = seq;
        frame[7] = nonceB;
        frame[8] = (byte)((seq ^ nonceB) ^ 0x01);  // all port 50001 packets use extra=0x01

        byte zzKey = frame[12];
        frame[14] = (byte)((helloAckNonce ^ K) ^ zzKey);
        return frame;
    }

    /// <summary>
    /// Variant of BuildCatCmd that also patches dec[9] (the cmd counter).
    /// Required for the RR1$/CH0$/DO< channel-open burst — each packet in each
    /// round must have a unique counter value or the SCU treats them as duplicates.
    /// </summary>
    public static byte[] BuildCatCmd(ReadOnlySpan<byte> template, byte seq,
                                      byte helloAckNonce, byte K, byte cmdCounter)
    {
        byte[] frame = BuildCatCmd(template, seq, helloAckNonce, K);
        byte zzKey = frame[12];
        frame[9 + 9] = (byte)(cmdCounter ^ zzKey);   // dec[9] = cmdCounter
        return frame;
    }

    /// <summary>
    /// Variant of BuildCatCmd that replaces the template's payload (dec[13:]) with
    /// custom bytes. Used for query commands like 0x15 'CG&lt;' (freq query) where
    /// the type/header structure is the same as the template but the payload differs.
    /// </summary>
    public static byte[] BuildCatCmd(ReadOnlySpan<byte> template, byte seq,
                                      byte helloAckNonce, byte K,
                                      ReadOnlySpan<byte> payloadOverride)
    {
        // Build the base frame with the template payload
        byte[] frame = BuildCatCmd(template, seq, helloAckNonce, K);

        // Replace dec[13:] with the override payload (XOR with ZZ key)
        byte zzKey = frame[12];
        int hdrEnd = 9 + 13;  // raw[9..21] = dec[0..12]
        // Resize frame if needed
        int newLen = hdrEnd + payloadOverride.Length;
        if (newLen != frame.Length)
        {
            byte[] resized = new byte[newLen];
            frame.AsSpan(0, hdrEnd).CopyTo(resized);
            frame = resized;
        }
        for (int i = 0; i < payloadOverride.Length; i++)
            frame[hdrEnd + i] = (byte)(payloadOverride[i] ^ zzKey);
        return frame;
    }

    /// <summary>
    /// Build a type 0x19 CAT send packet.
    /// dec structure: 0c 08 0f 00 08 [nonce^0x01] 0a 0b 04 [cmdCounter] 06 07 00 [catBytes]
    /// catBytes are raw ASCII CAT command bytes, e.g. "FA;" — NOT XOR'd.
    /// </summary>
    public static byte[] BuildCatSend(byte seq, byte helloAckNonce,
                                       byte cmdCounter, ReadOnlySpan<byte> catBytes)
    {
        // Payload (decoded):
        // [0-12] fixed header, [5]=nonce^0x01, [9]=cmdCounter
        // [13..] catBytes
        const byte zzKeyBase = 0x61; // typical ZZ key for type 0x19
        byte nonceB = NonceB(seq);

        // Build decoded payload
        int payloadLen = 13 + catBytes.Length;
        Span<byte> dec = stackalloc byte[payloadLen];
        dec[0] = 0x0c;
        dec[1] = 0x08;
        dec[2] = 0x0f;
        dec[3] = 0x00;
        dec[4] = 0x08;
        dec[5] = (byte)(helloAckNonce ^ 0x01);
        dec[6] = 0x0a;
        dec[7] = 0x0b;
        dec[8] = 0x04;
        dec[9] = cmdCounter;
        dec[10] = 0x06;
        dec[11] = 0x07;
        dec[12] = 0x00;
        catBytes.CopyTo(dec[13..]);

        // Encode: choose ZZ key = dec[3] XOR ... actually the ZZ key is raw[12] = dec[3] ^ key
        // For type 0x19, from the capture: the ZZ key is at dec[3]=0x00 position in payload
        // which means raw[12] = dec[3] ^ key — but we need to pick key carefully.
        // From captured packets: raw[12] varies. The simplest approach: use key = dec[3] since
        // dec[3] ^ key = raw[12], and we want raw[12] to be some value. From the capture
        // raw[12] = d6 for one packet. Let's use the nonce itself as the ZZ key basis.
        // Actually: ZZ key = raw[12]. It's just the byte at position 12 in the raw packet.
        // We can freely choose it. From capture: raw[12] of 0x19 varies.
        // Most consistent: set ZZ key = zzKeyBase and encode accordingly.
        byte key = zzKeyBase;

        byte[] frame = new byte[9 + payloadLen];
        frame[0] = 0x5a;
        frame[1] = 0x5a;
        frame[2] = 0x19;
        frame[3] = 0x00;
        frame[4] = 0x00;
        frame[5] = 0x01;
        frame[6] = seq;
        frame[7] = nonceB;
        frame[8] = (byte)((seq ^ nonceB) ^ 0x01);  // extra 0x01 confirmed for type 0x19
        for (int i = 0; i < payloadLen; i++)
            frame[9 + i] = (byte)(dec[i] ^ key);
        // Fix key position: raw[12] must equal the actual ZZ key we used
        frame[12] = key;

        return frame;
    }

