    ///   fun[18]   = 0x01            unknown fixed byte
    ///   fun[19:26]= 0x00 * 7        zero padding
    ///   fun[26:28]= 0x07d0          playback buffer (2000 ms) LE
    ///   fun[28:30]= 0x07d0          record buffer  (2000 ms) LE
    ///   fun[30]   = 0x64            volume 100
    ///   fun[31]   = 0x64            volume 100
    ///   fun[32:34]= 0x0000          zero
    ///
    /// The only fields that vary between modes are fun[12] (format) and fun[14:16] (rate).
    /// fun[10:12] = 0x0000 confirmed — earlier documentation of 0x0543 was incorrect.
    /// </summary>
    public static byte[] BuildSendAudioOpen(byte seq, byte helloAckNonce,
                                             AudioQuality quality = AudioQuality.Pcm16k,
                                             ushort dev = 2)
    {
        uint sid = (uint)(helloAckNonce ^ 0x08);
        const int dataLen = 28;
        byte[] buf = new byte[6 + dataLen];  // dev(2)+MID(2)+len(2)+data(28)

        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 0, dev);
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 2, 0x0105);   // MID_UsbAudio_Open
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 4, dataLen);

        // data[0:4] = SID
        BinaryPrimitives_WriteUInt32LE(buf.AsSpan(), 6, sid);

        // data[4:6] = 0x0000 (confirmed zero from four captures)
        // buf[10:12] already zero

        // data[6] = format, [7] = channels, [8:10] = sample rate LE
        (byte format, ushort sampleRate) = quality switch
        {
            AudioQuality.Pcm16k => ((byte)0x01, (ushort)16000),
            AudioQuality.ULaw16k => ((byte)0x03, (ushort)16000),
            AudioQuality.Pcm8k => ((byte)0x01, (ushort)8000),
            AudioQuality.ULaw8k => ((byte)0x03, (ushort)8000),
            _ => ((byte)0x01, (ushort)16000),
        };
        buf[12] = format;
        buf[13] = 0x02;  // stereo
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 14, sampleRate);

        // data[10:12] = 0x0000 (already zero)
        // data[12]    = 0x01   unknown fixed byte
        buf[18] = 0x01;
        // data[13:20] = 0x00 * 7 (already zero)
        // data[20:22] = playback buffer 2000 LE
        buf[26] = 0xd0;
        buf[27] = 0x07;
        // data[22:24] = record buffer 2000 LE
        buf[28] = 0xd0;
        buf[29] = 0x07;
        // data[24:26] = volume 100, 100
        buf[30] = 0x64;
        buf[31] = 0x64;
        // data[26:28] = 0x0000 (already zero)

        return BuildFunFrame(0x26, seq, buf);
    }

    internal static byte[] BuildFunFrame(byte typeByte, byte seq, ReadOnlySpan<byte> payload)
    {
        byte nonceB = NonceB(seq);
        byte[] frame = new byte[8 + payload.Length];
        frame[0] = 0x5a;
        frame[1] = 0x5a;
        frame[2] = typeByte;             // == (payload.Length + 4) & 0xff for our sizes
        frame[3] = 0x00;
        frame[4] = 0x00;
        frame[5] = 0x01;
        frame[6] = seq;
        frame[7] = nonceB;
        for (int i = 0; i < payload.Length; i++)
            frame[8 + i] = (byte)((((~i + 1) & 0xff) ^ payload[i]) ^ seq ^ nonceB);
        return frame;
    }

    // Helper: write LE uint16/uint32 to span (avoids System.Buffers dependency)
    private static void BinaryPrimitives_WriteUInt16LE(Span<byte> s, int off, uint v)
    {
        s[off] = (byte)v;
        s[off + 1] = (byte)(v >> 8);
    }
    private static void BinaryPrimitives_WriteUInt32LE(Span<byte> s, int off, uint v)
    {
        s[off] = (byte)v;
        s[off + 1] = (byte)(v >> 8);
        s[off + 2] = (byte)(v >> 16);
        s[off + 3] = (byte)(v >> 24);
    }

    private static byte[] BuildCatSetHeader(byte seq, byte helloAckNonce,
                                              byte cmdCounter, byte K)
    {
        // dec[0:13] for type 0x1e — differs from 0x19 header
        // dec[0-4] = 17 13 14 00 13  (confirmed from DLL trace)
        // dec[5]   = helloAckNonce ^ K
        // dec[6-8] = 11 10 1f        (confirmed)
        // dec[9]   = cmdCounter
        // dec[10-12] = 1d 1c 1b      (confirmed)
        return
        [
            0x17, 0x13, 0x14, 0x00, 0x13,
            (byte)(helloAckNonce ^ K),
            0x11, 0x10, 0x1f,
            cmdCounter,
            0x1d, 0x1c, 0x1b,
        ];
    }

    private static byte[] BuildCatSetKeys(string catCommand, byte K)
    {
        // For FA0<8digits>; format:
        //   'FA0' → K, K-1, K-2
        //   digits → 7,6,5,4,3,2,1,0 (count = len-4, starting from len-4-1)
        //   ';' → 0x0f
        int n = catCommand.Length;
        byte[] keys = new byte[n];
        // Prefix: first 3 chars use K countdown
        for (int i = 0; i < Math.Min(3, n - 1); i++)
            keys[i] = (byte)(K - i);
        // Middle digits: descending from (n-4) down to 0
        int digitCount = n - 4; // chars between prefix and terminator
        for (int i = 0; i < digitCount; i++)
            keys[3 + i] = (byte)(digitCount - 1 - i);
        // Terminator ';'
        if (n > 0)
            keys[n - 1] = 0x0f;
        return keys;
    }
