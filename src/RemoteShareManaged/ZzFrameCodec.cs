    /// <summary>
    /// Build a type 0x1e CAT SET command packet (PC→SCU).
    /// Used ONLY for SET commands (e.g. frequency change). Query commands
    /// (FA;, MD;, AI;) do not generate 0x1e packets — the SCU's 0x17/0x18
    /// stream provides current state.
    ///
    /// Encoding confirmed from DLL Wireshark trace (FA014350125;):
    ///   dec[5] = helloAckNonce ^ K  where K = 0x1a for type 0x1e
    ///   cat bytes encoding for FA0<8digits>;:
    ///     bytes 0-2  ('FA0'): XOR with K, K-1, K-2
    ///     bytes 3-10 (digits): XOR with 7,6,5,4,3,2,1,0
    ///     byte 11    (';'):   XOR with 0x0f
    ///
    /// ZZ key (raw[12]) = 0x1e, check_extra = 0x01
    /// </summary>
    public static byte[] BuildCatSet(byte seq, byte helloAckNonce, byte cmdCounter,
                                      string catCommand)
    {
        const byte K = 0x1a;
        const byte ZzKey = 0x1e;
        const byte extra = 0x01;
        const int HdrLen = 13;  // dec[0..12]

        byte[] catBytes = System.Text.Encoding.ASCII.GetBytes(catCommand);
        int totalDec = HdrLen + catBytes.Length;
        byte[] frame = new byte[9 + totalDec];

        // ZZ header (unencrypted)
        byte nonceB = NonceB(seq);
        frame[0] = 0x5a;
        frame[1] = 0x5a;
        frame[2] = 0x1e;
        frame[3] = 0x00;
        frame[4] = 0x00;
        frame[5] = 0x01;
        frame[6] = seq;
        frame[7] = nonceB;
        frame[8] = (byte)((seq ^ nonceB) ^ extra);

        // Build dec[0..12] header
        byte[] decHdr = BuildCatSetHeader(seq, helloAckNonce, cmdCounter, K);

        // Encode cat bytes: keys are K,K-1,K-2, then 7..0 per digit, then 0x0f for ';'
        byte[] catKeys = BuildCatSetKeys(catCommand, K);

        // XOR everything with ZzKey and write to frame payload (raw[9+])
        for (int i = 0; i < HdrLen; i++)
            frame[9 + i] = (byte)(decHdr[i] ^ ZzKey);
        for (int i = 0; i < catBytes.Length; i++)
            frame[9 + HdrLen + i] = (byte)((catBytes[i] ^ catKeys[i]) ^ ZzKey);

        return frame;
    }

    /// <summary>
    /// Build a type 0x13 logout packet (PC→SCU, port 50000).
    /// Confirmed from DLL Wireshark trace. Sent before closing the connection
    /// so the SCU properly closes the session (stops 0x18 broadcast, allows clean reconnect).
    /// K=0x47, extra=0x00, payload dec[13]=0x07.
    /// </summary>
    public static byte[] BuildLogout(byte seq, byte helloAckNonce)
    {
        const byte K = 0x47;
        const byte ZzKey = 0xa2;   // confirmed from DLL trace
        const byte Extra = 0x00;

        byte nonceB = NonceB(seq);
        return
        [
            // ZZ header
            0x5a, 0x5a, 0x13, 0x00, 0x00, 0x01,
            seq, nonceB, (byte)((seq ^ nonceB) ^ Extra),
            // Payload (dec[0:13] XOR ZzKey)
            (byte)(0x0a ^ ZzKey), (byte)(0x09 ^ ZzKey), (byte)(0x09 ^ ZzKey),
            (byte)(0x00 ^ ZzKey),  // dec[3]=0 always
            (byte)(0x0e ^ ZzKey),
            (byte)((helloAckNonce ^ K) ^ ZzKey),  // dec[5] = nonce^K
            (byte)(0x4d ^ ZzKey), (byte)(0x0d ^ ZzKey), (byte)(0x02 ^ ZzKey),
            (byte)(0x03 ^ ZzKey),  // dec[9] = counter (fixed at 3)
            (byte)(0x00 ^ ZzKey), (byte)(0x01 ^ ZzKey), (byte)(0x06 ^ ZzKey),
            // dec[13] = payload byte 0x07
            (byte)(0x07 ^ ZzKey),
        ];
    }

    /// <summary>
    /// Build a SendCatOpen packet (type 0x14, sent to port 50000).
    /// This is the FUN_10003c30-encoded registration packet that tells the SCU
    /// which client (SID) wants CAT data delivered to recvPort.
    /// SID = helloAckNonce ^ 0x08 (confirmed from multiple sessions).
    /// Sent twice (CONFIG A = seq N, CONFIG B = seq N+1), same content.
    /// </summary>
    public static byte[] BuildSendCatOpen(byte seq, byte helloAckNonce,
                                           ushort recvPort = 50001, uint baudRate = 38400, ushort dev = 1)
    {
        uint sid = (uint)(helloAckNonce ^ 0x08);

        // FUN_10003c30 internal buffer (16 bytes):
        // dev_id(2) + mid(2) + len(2) + sid(4) + recvPort(2) + baudRate(4)
        Span<byte> buf = stackalloc byte[16];
        BinaryPrimitives_WriteUInt16LE(buf, 0, dev);
        BinaryPrimitives_WriteUInt16LE(buf, 2, 0x0103);   // MID_UsbCat_Open
        BinaryPrimitives_WriteUInt16LE(buf, 4, 0x000a);   // data length = 10
        BinaryPrimitives_WriteUInt32LE(buf, 6, sid);
        BinaryPrimitives_WriteUInt16LE(buf, 10, recvPort);
        BinaryPrimitives_WriteUInt32LE(buf, 12, baudRate);

        return BuildFunFrame(0x14, seq, buf);
    }

    /// <summary>
    /// Build a SendDevPortConnect packet (type 0x0e, sent to port 50001).
    /// This is the FUN_10003c30-encoded connect packet that activates the CAT
    /// channel. It looks like a keepalive (type 0x0e, 18 bytes) but carries
    /// different payload — the SID and dev number.
    /// Sent once on port 50001 BEFORE RR1$/CH0$/DO<.
    /// </summary>
    public static byte[] BuildSendDevPortConnect(byte seq, byte helloAckNonce, ushort dev = 1)
    {
        uint sid = (uint)(helloAckNonce ^ 0x08);

        // FUN_10003c30 internal buffer (10 bytes):
        // dev_id(2) + mid(2) + len(2) + sid(4)
        Span<byte> buf = stackalloc byte[10];
        BinaryPrimitives_WriteUInt16LE(buf, 0, dev);
        BinaryPrimitives_WriteUInt16LE(buf, 2, 0x0104);   // MID_UsbCat_Connect
        BinaryPrimitives_WriteUInt16LE(buf, 4, 0x0004);   // data length = 4
        BinaryPrimitives_WriteUInt32LE(buf, 6, sid);

        return BuildFunFrame(0x0e, seq, buf);
    }

    /// <summary>
    /// Build a session confirm packet (FUN 0x12, MID=0x0105) sent after AI1;
    /// to complete the CAT channel handshake.
    /// pktId = 2 for the confirm step (confirmed from trace).
    /// </summary>
    public static byte[] BuildSendCatConfirm(byte seq, byte helloAckNonce, ushort pktId, ushort dev = 1)
    {
        uint sid = (uint)(helloAckNonce ^ 0x08);
        // Internal buf: dev(2)+mid(2)+len(2)+sid(4)+pktId(4) = 14 bytes
        byte[] buf = new byte[14];
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 0, dev);
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 2, 0x0105);
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 4, 0x0008);  // len=8
        BinaryPrimitives_WriteUInt32LE(buf.AsSpan(), 6, sid);
        BinaryPrimitives_WriteUInt32LE(buf.AsSpan(), 10, pktId);
        return BuildFunFrame(0x16, seq, buf);  // 0x16 = (14+4)&0xff
    }

    /// <summary>
    /// Build a SendCatWrite packet (FUN_10003c30 format, port 50001).
    /// MID = 0x0105 (MID_UsbCat_Write). Carries ASCII CAT command bytes.
    /// pktId increments with each write (1-based).
    /// Type byte: 0x16 for 14+ byte payload, 0x15 for 11-13 byte payload.
    /// </summary>
    public static byte[] BuildSendCatWrite(byte seq, byte helloAckNonce,
                                            ushort pktId, byte[] catCmd, ushort dev = 1)
    {
        uint sid = (uint)(helloAckNonce ^ 0x08);
        // len = SID(4) + pktId(4) + catCmd bytes — confirmed from Yaesu trace
        int dataLen = 8 + catCmd.Length;

        // Internal buffer: dev(2)+mid(2)+len(2)+sid(4)+pktId(4)+catBytes
        byte[] buf = new byte[6 + 4 + 4 + catCmd.Length];
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 0, dev);
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 2, 0x0105);  // MID_UsbCat_Write
        BinaryPrimitives_WriteUInt16LE(buf.AsSpan(), 4, (uint)dataLen);
        BinaryPrimitives_WriteUInt32LE(buf.AsSpan(), 6, sid);
        BinaryPrimitives_WriteUInt32LE(buf.AsSpan(), 10, pktId);
        catCmd.CopyTo(buf, 14);

        // Type: 0x16 if frame >= 26 bytes total (8+18), else 0x15
        byte frameType = (byte)((buf.Length + 4) & 0xff);  // matches FUN frame convention
        return BuildFunFrame(frameType, seq, buf);
    }
    /// Wire format: 5a5a [type] 00 00 01 [seq] [nonceB] [encoded_payload...]
    /// Actually: 5a5a [len+4 lo] [len+4 hi] 00 01 [seq] [nonceB] [payload]
    /// where type == len+4 lo byte (they happen to collide for these packet sizes).
    /// Payload byte[i] = (~i+1 & 0xff) ^ src[i] ^ seq ^ nonceB
    /// </summary>
    /// <summary>
    /// Build a SendDevPortConnect packet for port 50002 (audio).
    /// Identical structure to the CAT SendDevPortConnect but with dev=2 (UsbAudio)
    /// and MID=0x0104. Sent once to port 50002; SCU ACKs with 0x0e MID=0x0184.
    /// Confirmed from Yaesu RX-only capture.
    /// </summary>
    public static byte[] BuildSendAudioConnect(byte seq, byte helloAckNonce, ushort dev = 2)
    {
        uint sid = (uint)(helloAckNonce ^ 0x08);
        Span<byte> buf = stackalloc byte[10];
        BinaryPrimitives_WriteUInt16LE(buf, 0, dev);
        BinaryPrimitives_WriteUInt16LE(buf, 2, 0x0104);   // MID_UsbAudio_Connect
        BinaryPrimitives_WriteUInt16LE(buf, 4, 0x0004);   // data length = 4
        BinaryPrimitives_WriteUInt32LE(buf, 6, sid);
        return BuildFunFrame(0x0e, seq, buf);
    }

